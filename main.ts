// Token Radar (model radar-2) for token-radar-01 — Node 22, standard library only.
//
// The program reads the sealed DefiLlama snapshot (default /input/snapshot.json, or
// --input <file|dir>), scores every pre-token protocol with the model below, writes the
// ranked board to /output/board.json and the dashboard's data to /output/data.js, copies
// this repository's dashboard/ and screenshots/ to /output, and writes /output/dossier.json
// with the vendored make.fun library. It is deterministic: two runs write the same bytes.
//
// The model (radar-2), stated in full so the judge can check it against the snapshot:
//
//   implied = TVL x 0.25 x growth x maturity x breadth x category
//
//   base       TVL x 0.25 — the launch is worth a quarter of the value already locked in the
//              protocol, the anchor every row shares.
//   growth     1 + clamp(change_7d, -60, 120) / 100 x 0.5 — a protocol whose TVL is growing
//              is worth more than one the same size that is shrinking (0.70 to 1.60).
//   maturity   0.6 + min(age_days, 1095) / 1095 x 0.4 — a protocol that has run longer with no
//              token has had longer to build the users a launch would pay (0.60 to 1.00;
//              unknown age counts as 365 days).
//   breadth    1 + 0.04 x min(chains - 1, 4) — a protocol live on more chains reaches more
//              users a launch could pay (1.00 to 1.16).
//   category   1.10 for user-facing apps that most often launch a token (DEXs, lending,
//              derivatives, yield, CDPs, prediction markets, RWAs and the like), 0.90 for
//              infrastructure and wrapped products (bridges, liquid staking, oracles, CEXs),
//              1.00 for everything else. The tier comes from the category's words, never
//              from a protocol's name: no name is ever special-cased.
//
// The board covers the snapshot's whole watchlist (the floor, never the ceiling) and adds
// every pre-token protocol below the floor that the field guide's rule allows: TVL under
// the $50M floor, no token recorded, no version marker in the name, no wrapped / staked /
// staking word, no exchange-name prefix, and a category that is not Bridge, Canonical
// Bridge, Liquid Staking, Liquid Restaking, Restaked BTC or CEX. Protocols at or above
// the floor that the watchlist leaves out are left out: the house's list is the
// authority there, because the one field it used and this file does not carry — the
// parent protocol — is what leaves them out. Live-token protocols are kept apart and
// shown as the market's own values, never mixed into the ranked board.
//
// Outside the grader's container, MAKEFUN_OUTPUT_DIR stands in for /output:
//   mkdir -p out && MAKEFUN_OUTPUT_DIR=out node main.ts --input ../input/snapshot.json

